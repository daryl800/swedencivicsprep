const characterReplacements: Record<string, string> = Object.fromEntries(characterReplacementPairs);

export function toTraditionalChinese<T>(value: T): T {
  if (typeof value === "string") {
    return convertString(value) as T;
  }

  if (Array.isArray(value)) {
    return value.map((item) => toTraditionalChinese(item)) as T;
  }

  if (typeof value === "function") {
    return ((...args: unknown[]) => toTraditionalChinese((value as (...args: unknown[]) => unknown)(...args))) as T;
  }

  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value as Record<string, ConvertibleValue>).map(([key, entry]) => [key, toTraditionalChinese(entry)])
    ) as T;
  }

  return value;
}

function convertString(value: string) {
  let converted = value;
  for (const [simplified, traditional] of phraseReplacements) {
    converted = converted.split(simplified).join(traditional);
  }
  return Array.from(converted).map((character) => characterReplacements[character] || character).join("");
}
